export type MarketingSocialBrand = "Discord" | "Instagram" | "TikTok"

export function MarketingSocialBrandIcon({
  brand,
  className,
}: Readonly<{ brand: MarketingSocialBrand; className?: string }>) {
  switch (brand) {
    case "Discord":
      return <DiscordBrandIcon className={className} />
    case "Instagram":
      return <InstagramBrandIcon className={className} />
    case "TikTok":
      return <TikTokBrandIcon className={className} />
    default: {
      const unreachable: never = brand
      return unreachable
    }
  }
}
